-- =============================================================================
-- Módulo Marketing – esquema H2/PostgreSQL
-- =============================================================================

-- canal --------------------------------------------------------------------
CREATE TABLE canal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL UNIQUE,
    tipo VARCHAR(255)
);

-- producto ----------------------------------------------------------------
CREATE TABLE producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    codigo VARCHAR(255) NOT NULL UNIQUE
);

-- Campania -----------------------------------------------------------------
-- estado: enum EstadoCampania → PLANIFICADA | ACTIVA | FINALIZADA
CREATE TABLE campania (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE NOT NULL,
    presupuesto DECIMAL(12,2) NOT NULL CHECK (presupuesto >= 0),
    costo DECIMAL(12,2) NOT NULL CHECK (costo >= 0),
    roi DECIMAL(12,2),
    estado VARCHAR(50) NOT NULL CHECK (estado IN ('PLANIFICADA', 'ACTIVA', 'FINALIZADA')),
    creado_en TIMESTAMP,
    actualizado_en TIMESTAMP
);

-- empresa ------------------------------------------------------------------
CREATE TABLE empresa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    razon_social VARCHAR(255),
    cuit VARCHAR(255) UNIQUE,
    direccion VARCHAR(255)
);

-- lead_comercial -----------------------------------------------------------
-- etapa: enum EtapaPipeline → NUEVO | CONTACTADO | CALIFICADO | CONVERTIDO | PERDIDO
-- resultado_cierre: enum ResultadoCierre → GANADO | PERDIDO
CREATE TABLE lead_comercial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    empresa_id BIGINT,
    etapa VARCHAR(50) NOT NULL CHECK (etapa IN ('NUEVO', 'CONTACTADO', 'CALIFICADO', 'CONVERTIDO', 'PERDIDO')),
    canal_id BIGINT NOT NULL,
    canal_anterior_id BIGINT,
    campania_id BIGINT NOT NULL,
    resultado_cierre VARCHAR(50) CHECK (resultado_cierre IN ('GANADO', 'PERDIDO')),
    motivo_perdida VARCHAR(1000),
    creado_en TIMESTAMP,
    actualizado_en TIMESTAMP,
    CONSTRAINT fk_lead_empresa FOREIGN KEY (empresa_id) REFERENCES empresa(id),
    CONSTRAINT fk_lead_canal FOREIGN KEY (canal_id) REFERENCES canal(id),
    CONSTRAINT fk_lead_canal_anterior FOREIGN KEY (canal_anterior_id) REFERENCES canal(id),
    CONSTRAINT fk_lead_campania FOREIGN KEY (campania_id) REFERENCES campania(id)
);

-- contacto (información de contacto 1:1 con lead) -------------------------
CREATE TABLE contacto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id BIGINT NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL,
    telefono VARCHAR(100),
    CONSTRAINT fk_contacto_lead FOREIGN KEY (lead_id) REFERENCES lead_comercial(id)
);

-- campania_producto (N:M entre Campania y Producto) -----------------------
CREATE TABLE campania_producto (
    campania_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    PRIMARY KEY (campania_id, producto_id),
    CONSTRAINT fk_cp_campania FOREIGN KEY (campania_id) REFERENCES campania(id),
    CONSTRAINT fk_cp_producto FOREIGN KEY (producto_id) REFERENCES producto(id)
);

-- campania_canal (N:M entre Campania y Canal) ----------------------------
CREATE TABLE campania_canal (
    campania_id BIGINT NOT NULL,
    canal_id BIGINT NOT NULL,
    PRIMARY KEY (campania_id, canal_id),
    CONSTRAINT fk_cc_campania FOREIGN KEY (campania_id) REFERENCES campania(id),
    CONSTRAINT fk_cc_canal FOREIGN KEY (canal_id) REFERENCES canal(id)
);

-- lead_producto (N:M entre LeadComercial y Producto) ----------------------
CREATE TABLE lead_producto (
    lead_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    PRIMARY KEY (lead_id, producto_id),
    CONSTRAINT fk_lp_lead FOREIGN KEY (lead_id) REFERENCES lead_comercial(id),
    CONSTRAINT fk_lp_producto FOREIGN KEY (producto_id) REFERENCES producto(id)
);

-- Índices para consultas frecuentes ---------------------------------------
CREATE INDEX idx_campania_nombre ON campania(nombre);
CREATE INDEX idx_campania_fecha_inicio ON campania(fecha_inicio);
CREATE INDEX idx_campania_fecha_fin ON campania(fecha_fin);
CREATE INDEX idx_campania_estado ON campania(estado);
CREATE INDEX idx_lead_campania_id ON lead_comercial(campania_id);
CREATE INDEX idx_lead_canal_id ON lead_comercial(canal_id);
CREATE INDEX idx_lead_empresa_id ON lead_comercial(empresa_id);
CREATE INDEX idx_lead_etapa ON lead_comercial(etapa);
